CREATE TABLE IF NOT EXISTS tabdeal_local_paper_signals (
  symbol TEXT NOT NULL,
  strategy_version TEXT NOT NULL,
  candle_open_ms INTEGER NOT NULL,
  candle_close_ms INTEGER NOT NULL,
  continuity_epoch INTEGER NOT NULL,
  signal TEXT NOT NULL CHECK (signal IN ('WAIT', 'BUY_CANDIDATE')),
  reason TEXT NOT NULL,
  paper_eligible INTEGER NOT NULL DEFAULT 0 CHECK (paper_eligible IN (0, 1)),
  entry_price REAL,
  reference_notional_usdt REAL,
  entry_quantity REAL,
  entry_spread_bps REAL,
  entry_observed_at_ms INTEGER,
  indicators_json TEXT NOT NULL,
  quality_json TEXT NOT NULL,
  book_json TEXT,
  markout_5m_close_price REAL,
  markout_5m_modeled_exit_price REAL,
  markout_5m_gross_bps REAL,
  markout_5m_net_bps_fee10 REAL,
  markout_5m_net_bps_fee20 REAL,
  markout_5m_net_bps_fee40 REAL,
  markout_15m_close_price REAL,
  markout_15m_modeled_exit_price REAL,
  markout_15m_gross_bps REAL,
  markout_15m_net_bps_fee10 REAL,
  markout_15m_net_bps_fee20 REAL,
  markout_15m_net_bps_fee40 REAL,
  markout_60m_close_price REAL,
  markout_60m_modeled_exit_price REAL,
  markout_60m_gross_bps REAL,
  markout_60m_net_bps_fee10 REAL,
  markout_60m_net_bps_fee20 REAL,
  markout_60m_net_bps_fee40 REAL,
  created_at_ms INTEGER NOT NULL,
  updated_at_ms INTEGER NOT NULL,
  PRIMARY KEY (symbol, strategy_version, candle_open_ms)
);

CREATE INDEX IF NOT EXISTS idx_tabdeal_local_paper_pending
  ON tabdeal_local_paper_signals (symbol, strategy_version, paper_eligible, candle_open_ms DESC);
